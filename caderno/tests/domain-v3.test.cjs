const assert=require('node:assert/strict');
const C=require('../core.js'),P=require('../parser.js');
const base=C.empty();
const record={id:'demo-a',farm:'Bananal',os:'91',type:'Terrestre',start:'2026-11-11',end:'2026-11-11',complete:true,lots:['BD1','BD2'],products:[{name:'Exemplo X',dose:0.3,doseUnit:'kg/ha',used:'200',usedUnit:'kg',left:'0',leftUnit:'kg'}]};
const source={...base,records:[record],lots:[{id:'BD1',farm:'Bananal'},{id:'BD2',farm:'Bananal'}],catalog:[{name:'Exemplo X',unit:'kg'}],audit:[{at:'2026-11-11T11:00:00Z',action:'Revisado',detail:'Exemplo'}]};
const loaded=C.safeImport(base,source);assert.equal(loaded.added,1);assert.equal(loaded.skipped,0);assert.equal(loaded.data.audit.length,1);
assert.equal(C.safeImport(loaded.data,source).added,0,'não duplicar');assert.equal(C.safeImport(loaded.data,source).data.audit.length,1,'não duplicar auditoria');
assert.equal(C.frequentBlocks(loaded.data,'Bananal')[0].lots.join(','),'BD1,BD2');
assert.equal(C.suggestDose(loaded.data,'Exemplo X','Bananal',['BD1'])[0].unit,'kg/ha');
const damaged={...source,records:[{os:'92',farm:'Bananal',lots:[],products:[],start:''}]};
const quarantine=C.safeImport(base,damaged);assert.equal(quarantine.added,0);assert.equal(quarantine.quarantined,1);assert.equal(quarantine.data.quarantine.length,1);assert(quarantine.details[0].reason);
assert(C.validateRecord({...record,used:'0'}).length===0);
assert(C.validateRecord({...record,end:'',complete:false}).length===0,'OS em aberto pode não ter fim');
assert(C.validateRecord({...record,end:'',complete:true}).length>0,'OS concluída exige término');
assert.deepEqual(P.parseLots('RA12'),['RA12']);assert.deepEqual(P.parseLots('P10'),['P10']);
assert.deepEqual(P.parseLots('BD12345'),['BD1','BD2','BD3','BD4','BD5']);
assert.deepEqual(P.parseLots('RA - RB - RC 7, 8'),['RA7','RA8','RB7','RB8','RC7','RC8']);
assert.deepEqual(P.parseLots('BE2-3'),['BE2','BE3']);
assert.deepEqual(P.parseLots('RA4  5 6'),['RA4','RA5','RA6']);
assert.equal(P.lineProduct('Zapp---200KG').unit,'kg');assert.equal(P.lineProduct('Áureo---20L').unit,'L');
assert.equal(P.lineProduct('Kellus---2,5G').unit,'g');
assert(P.ambiguousLots('RA12',[{id:'RA1'},{id:'RA2'}]).length>0,'ambiguidades são avisadas, não adivinhadas');
const voided={...record,voided:true};assert.equal(C.filter([record,voided],{}).length,1);
assert.equal(C.filter([record,voided],{includeVoided:true}).length,2);
console.log('OK: parser sem ambiguidades, unidades, doses históricas, blocos, backup auditável, quarentena, situação e anuladas');
